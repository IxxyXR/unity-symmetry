"""Precompute compact lattice-equivalent space-group representatives using only stdlib.

Run after regenerating SpaceGroupData.cs or SpaceGroupDomainData.cs. The identity
stays fixed; every other operation may move only by integer primitive periods.
Prefer a face-connected, filled and regular-looking repeat cluster. This bounded
deterministic search uses natural domain centers and shared faces, without
claiming globally optimal packings.
"""

from argparse import ArgumentParser
from fractions import Fraction
from itertools import product
from pathlib import Path
import re

SCALE = 48  # Exact for all domain vertices, twelfths and primitive basis vectors.
BASIS = {
    "P": ((1, 0, 0), (0, 1, 0), (0, 0, 1)),
    "A": ((1, 0, 0), (0, 0.5, -0.5), (0, 0.5, 0.5)),
    "B": ((0.5, 0, -0.5), (0, 1, 0), (0.5, 0, 0.5)),
    "C": ((0.5, -0.5, 0), (0.5, 0.5, 0), (0, 0, 1)),
    "I": ((-0.5, 0.5, 0.5), (0.5, -0.5, 0.5), (0.5, 0.5, -0.5)),
    "F": ((0, 0.5, 0.5), (0.5, 0, 0.5), (0.5, 0.5, 0)),
    "R": (
        (Fraction(2, 3), Fraction(1, 3), Fraction(1, 3)),
        (Fraction(-1, 3), Fraction(1, 3), Fraction(1, 3)),
        (Fraction(-1, 3), Fraction(-2, 3), Fraction(1, 3)),
    ),
}
SHIFTS = sorted(
    product(range(-2, 3), repeat=3), key=lambda n: (sum(x * x for x in n), n)
)
ZERO = SHIFTS.index((0, 0, 0))
RUNTIME = Path("Packages/UnitySymmetry/com.ixxy.unitysymmetry/Wallpaper/Runtime")


def integral(value):
    assert int(value) == value, f"Coordinate is not exact at scale {SCALE}: {value}"
    return int(value)


def load_groups(root):
    source = (root / RUNTIME / "SpaceGroupData.cs").read_text(encoding="utf-8-sig")
    names = re.findall(r'"([^"]+)"', source.split("Names = {", 1)[1].split("};", 1)[0])
    operations = [
        list(map(int, re.findall(r"-?\d+", block)))
        for block in re.findall(r"new sbyte\[\] \{(.*?)\}", source, re.S)
    ]
    domains = (root / RUNTIME / "SpaceGroupDomainData.cs").read_text(
        encoding="utf-8-sig"
    )
    vertices = [
        [
            tuple(
                integral(Fraction(c.strip().replace("f", "")) * SCALE)
                for c in vertex.split(",")
            )
            for vertex in re.findall(r"new Vector3\(([^)]+)\)", block)
        ]
        for block in re.findall(r"new Vector3\[\] \{(.*?)\}", domains, re.S)
    ]
    assert len(names) == len(operations) == len(vertices) == 230
    return zip(names, operations, vertices)


def compact(number, name, raw, vertices):
    from space_group_packing import pack

    hexagonal = 143 <= number <= 194

    def cartesian(point):
        if not hexagonal:
            return point
        assert point[1] % 2 == 0
        return point[0] - point[1] // 2, point[1], point[2]

    lattice = [
        cartesian(
            tuple(
                integral(
                    SCALE
                    * sum(
                        Fraction(n[j]) * Fraction(BASIS[name[0]][j][k])
                        for j in range(3)
                    )
                )
                for k in range(3)
            )
        )
        for n in SHIFTS
    ]
    seen, copies = set(), []
    for offset in range(0, len(raw), 12):
        operation = raw[offset : offset + 12]
        rotation = tuple(operation[:9])
        if rotation in seen:
            continue
        seen.add(rotation)
        copies.append(
            [
                cartesian(
                    tuple(
                        sum(rotation[k * 3 + j] * v[j] for j in range(3))
                        + operation[9 + k] * (SCALE // 12)
                        for k in range(3)
                    )
                )
                for v in vertices
            ]
        )
    assert raw[:12] == [1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 0, 0]
    chosen, shared_area = pack(
        [cartesian(v) for v in vertices], copies, lattice, SHIFTS, ZERO, hexagonal
    )
    shifts = [SHIFTS[j] for j in chosen]
    assert shifts[0] == (0, 0, 0)
    assert len(shifts) == len(seen)
    assert all(
        isinstance(c, int) and -128 <= c <= 127 for shift in shifts for c in shift
    )
    return shifts, shared_area


def generate(root):
    lines = [
        "// Generated by Tools/generate_space_group_representatives.py; do not edit.",
        "// Whole primitive-lattice shifts for the first operation of each distinct rotation.",
        "// Empty rows retain the database representatives. The identity always has zero shift.",
        "internal static class SpaceGroupRepresentativeData",
        "{",
        "    internal static readonly sbyte[][] PrimitiveShifts =",
        "    {",
    ]
    improved = []
    for number, (name, operations, vertices) in enumerate(load_groups(root), 1):
        shifts, _ = compact(number, name, operations, vertices)
        changed = any(shift != (0, 0, 0) for shift in shifts)
        values = ", ".join(str(c) for shift in shifts for c in shift) if changed else ""
        lines.append(f"        // {number}: {name}")
        lines.append(f"        new sbyte[] {{ {values} }},")
        if changed:
            improved.append(number)
    lines += ["    };", "}", ""]
    return "\n".join(lines), improved


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", type=Path, default=Path(__file__).resolve().parents[1]
    )
    parser.add_argument("--output", type=Path)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify the generated table is current without writing it",
    )
    args = parser.parse_args()
    output = args.output or args.root / RUNTIME / "SpaceGroupRepresentativeData.cs"
    text, improved = generate(args.root)
    if args.check:
        assert output.read_text(encoding="utf-8-sig") == text, f"Regenerate {output}"
    else:
        output.write_text(text, encoding="utf-8", newline="\n")
    print(
        f"Validated 230 groups; updated {len(improved)}; face connectivity, identity and lattice classes preserved."
    )
    print(f"Improved group numbers: {','.join(map(str, improved))}")


if __name__ == "__main__":
    main()
